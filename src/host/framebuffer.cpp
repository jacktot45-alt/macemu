const uint8_t* glyphFor(char c) {
    unsigned char u = static_cast<unsigned char>(c);
    if (u >= 'a' && u <= 'z') u = static_cast<unsigned char>(u - 32);
    if (u < 32 || u > 95) u = '?';
    return kFont8x8[u - 32];
}

