void Framebuffer::resize(int w, int h) {
    if (w < 1) w = 1;
    if (h < 1) h = 1;
    width = w;
    height = h;
    pixels.assign(static_cast<size_t>(w) * static_cast<size_t>(h), 0x000000u);
}

void Framebuffer::clear(uint32_t color) {
    for (auto& p : pixels) p = color;
}

void Framebuffer::setPixel(int x, int y, uint32_t color) {
    if (x < 0 || y < 0 || x >= width || y >= height) return;
    pixels[static_cast<size_t>(y) * width + x] = color;
}

uint32_t Framebuffer::getPixel(int x, int y) const {
    if (x < 0 || y < 0 || x >= width || y >= height) return 0;
    return pixels[static_cast<size_t>(y) * width + x];
}

void Framebuffer::fillRect(int x, int y, int w, int h, uint32_t color) {
    if (w < 0) { x += w; w = -w; }
    if (h < 0) { y += h; h = -h; }
    int x0 = std::max(0, x), y0 = std::max(0, y);
    int x1 = std::min(width, x + w), y1 = std::min(height, y + h);
    for (int yy = y0; yy < y1; ++yy)
        for (int xx = x0; xx < x1; ++xx) pixels[static_cast<size_t>(yy) * width + xx] = color;
}

void Framebuffer::frameRect(int x, int y, int w, int h, uint32_t color) {
    if (w <= 0 || h <= 0) return;
    for (int xx = x; xx < x + w; ++xx) {
        setPixel(xx, y, color);
        setPixel(xx, y + h - 1, color);
    }
    for (int yy = y; yy < y + h; ++yy) {
        setPixel(x, yy, color);
        setPixel(x + w - 1, yy, color);
    }
}

void Framebuffer::drawLine(int x0, int y0, int x1, int y1, uint32_t color) {
    int dx = std::abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -std::abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    for (;;) {
        setPixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

int Framebuffer::drawText(int x, int y, const std::string& text, uint32_t color, int scale,
                          bool opaque, uint32_t bgColor) {
    if (scale < 1) scale = 1;
    int cursor = x;
    for (char c : text) {
        if (c == '\n') {
            y += 8 * scale;
            cursor = x;
            continue;
        }
        const uint8_t* g = glyphFor(c);
        for (int row = 0; row < 8; ++row) {
            for (int col = 0; col < 8; ++col) {
                bool on = (g[row] >> (7 - col)) & 1;
                if (!on && !opaque) continue;
                uint32_t px = on ? color : bgColor;
                for (int sy = 0; sy < scale; ++sy)
                    for (int sx = 0; sx < scale; ++sx)
                        setPixel(cursor + col * scale + sx, y + row * scale + sy, px);
            }
        }
        cursor += 8 * scale;
    }
    return cursor - x;
}

int Framebuffer::textWidth(const std::string& text, int scale) {
    if (scale < 1) scale = 1;
    return static_cast<int>(text.size()) * 8 * scale;
}

int Framebuffer::textHeight(int scale) { return 8 * (scale < 1 ? 1 : scale); }

bool Framebuffer::writePpm(const std::string& path) const {
    FILE* f = std::fopen(path.c_str(), "wb");
    if (!f) return false;
    std::fprintf(f, "P6\n%d %d\n255\n", width, height);
    for (uint32_t p : pixels) {
        uint8_t rgb[3] = {static_cast<uint8_t>((p >> 16) & 0xFF),
                          static_cast<uint8_t>((p >> 8) & 0xFF),
                          static_cast<uint8_t>(p & 0xFF)};
        std::fwrite(rgb, 1, 3, f);
    }
    std::fclose(f);
    return true;
}

